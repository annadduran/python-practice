cadena = "Te quiero solo como amigo"

#los dos primeros caracteres
print(cadena[0:2])
#los tres ultimos caracteres
print(cadena[22 : ])
print(cadena[-3 : ])
#imprma cada dos caracteres
print(cadena[::2])
#sentido inverso
print(cadena[::-1])
#en un sentido y en un sentido inverso
print(cadena+cadena[::-1])


